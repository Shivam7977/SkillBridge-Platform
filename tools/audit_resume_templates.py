"""Static text audit of resume template coverage and JavaScript selectors.

This intentionally does not import Flask/app.py: importing the app connects to
configured services. Jinja is treated as text; no HTML/Jinja parser is used.
"""
from __future__ import annotations

import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

BUILDER = ROOT / "templates" / "resume_builder.html"
PDF_TEMPLATE = ROOT / "templates" / "resume_pdf.html"
REPORT = ROOT / "audit_report.md"


def section_labels(block: str) -> list[str]:
    return [re.sub(r"\s+", " ", re.sub(r"<[^>]*>", "", value)).strip()
            for value in re.findall(r'class=["\']st["\']\s*>(.*?)</', block, re.I | re.S)]


def has_any(text: str, patterns: tuple[str, ...]) -> bool:
    return any(re.search(pattern, text, re.I | re.S) for pattern in patterns)


def main() -> int:
    source = BUILDER.read_text(encoding="utf-8")
    pdf_source = PDF_TEMPLATE.read_text(encoding="utf-8")
    pdf_template_count = len(re.findall(r'<div\s+id=["\']t\d+["\'][^>]*>', pdf_source, re.I))
    template_matches = list(re.finditer(r'<div\s+id=["\']t(\d+)["\'][^>]*>', source, re.I))
    templates: dict[int, str] = {}
    for index, match in enumerate(template_matches):
        end = template_matches[index + 1].start() if index + 1 < len(template_matches) else source.find("<!-- closes: previewInner")
        if end < 0:
            end = len(source)
        templates[int(match.group(1))] = source[match.start():end]

    id_counts = Counter(re.findall(r'\bid\s*=\s*["\']([^"\']+)["\']', source, re.I))
    duplicates = {key: count for key, count in sorted(id_counts.items()) if count > 1}

    # Literal IDs passed to getElementById and literal #id selectors. Dynamic
    # concatenations such as 't' + n and 'ep-proj-title-' + i are listed below.
    js = source[source.find("<script>"):]
    referenced = set(re.findall(r'getElementById\(\s*["\']([^"\']+)["\']\s*\)', js))
    referenced.update(re.findall(r'querySelector(?:All)?\(\s*["\']#([A-Za-z][\w:-]*)', js))
    dynamic_pattern = r"""getElementById\(\s*(['"])(.*?)\1\s*\+"""
    dynamic_refs = sorted(set(re.findall(dynamic_pattern, js)))
    dynamic_refs = [value[1] for value in dynamic_refs]
    markup_ids = set(id_counts)
    missing = sorted(referenced - markup_ids)

    categories = {
        "Name/header": (r'class=["\'][^"\']*(?:nm|h-name|t19-name)[^"\']*["\']',),
        "Summary/about": (r'about_me|t19-summary',),
        "Career goal": (r'career_goal',),
        "Experience": (r'work_experience|>Experience</|>experience</',),
        "Education": (r'\beducation\b|>Education</|>education</',),
        "Skills": (r'known_skills|>Skills</|>Tech Stack</|>Core Competencies</|>Stack</',),
        "Learning skills": (r'learning_skills|>Learning</|>Exploring</|>Currently Learning:',),
        "Projects": (r'\bprojects\b|>Projects</|>Projects \(',),
        "Certificates": (r'certificates|>Certifications</|>Certificates</|>Credentials</|>Achievements',),
        "Links/contact": (r'\b(?:email|location|linkedin_url|github_url)\b|t19-contact',),
    }

    rows = []
    for number, block in sorted(templates.items()):
        labels = section_labels(block)
        label_text = "; ".join(labels) if labels else "(Clean ATS uses t19-* classes; no .st labels)"
        present = [name for name, pats in categories.items() if has_any(block, pats)]
        if number == 2:
            hooks = "t19-name/contact/summary/edu/exp/tech; project uses t19-proj-*"
        else:
            hooks = ".nm/.h-name; .role/.h-role; .sec/.st; .pj/.pt/.pd; .exp-item; .edu-item"
        escaped_labels = label_text.replace("|", "\\|")
        rows.append(f"| {number} | {escaped_labels} | {', '.join(present)} | {hooks} |")

    chooser_count = len(re.findall(r'onclick=["\']sw\(\d+,this\)', source))

    lines = [
        "# Resume template static audit",
        "",
        "> Generated by `tools/audit_resume_templates.py`. Static text scan only: Jinja is not rendered, Flask is not imported, and no browser behavior is exercised.",
        "",
        "## Counts",
        "",
        f"- Builder template blocks (`id=\"tN\"`): **{len(templates)}** ({', '.join(map(str, sorted(templates)))})",
        f"- PDF template blocks (`id=\"tN\"`): **{pdf_template_count}**",
        f"- Template chooser cards (`sw(N,this)`): **{chooser_count}**",
        f"- Literal IDs in builder source: **{sum(id_counts.values())} occurrences / {len(id_counts)} distinct**",
        f"- Duplicate literal IDs: **{len(duplicates)}**",
        f"- Literal JavaScript ID references missing from markup: **{len(missing)}**",
        "",
        "## Duplicate IDs",
        "",
        "| ID | Occurrences |",
        "|---|---:|",
    ]
    lines.extend([f"| `{key}` | {count} |" for key, count in duplicates.items()] or ["| *(none found)* | 0 |"])
    lines += ["", "## JavaScript literal IDs missing from markup", "", "| ID |", "|---|"]
    lines.extend([f"| `{value}` |" for value in missing] or ["| *(none found)* |"])
    lines += ["", f"Dynamic ID expressions requiring manual interpretation: {', '.join('`'+item+'`' for item in dynamic_refs) or 'none found'}.", "", "## Per-template section coverage", "", "| Template | Section labels in source | Sections detected by text | Expected shared hooks |", "|---:|---|---|---|"]
    lines.extend(rows)
    lines += [
        "",
        "## Static findings to verify in browser",
        "",
        "- Template 2 (Clean ATS) uses `t19-*` hooks while the shared update path targets `.sec/.st`, `.pj/.pt/.pd`, `.exp-item`, and `.edu-item`; its dedicated `cur === 2` branch handles several sections but not project editing or learning-skill editing.",
        "- Template 6 (Data Scientist) renders skills as `.bar-row/.bar-lbl` bars; `rebuildTags()` requires a pill/chip/sk/badge sample, so the shared skills rebuild has no matching sample there.",
        "- Template 3 (Minimal Pro) has a Profile summary paragraph without `p.about`, but `Profile` is a recognized label and the existing `<p>` is updated by the label-based path.",
        "- Templates 9, 11, and 15 use semantic labels not recognized by the shared goal/skills label lists: Design Vision, Competencies, What I Seek, and Disciplines.",
        "- The Years of Experience panel field is populated and has an oninput callback, but `liveUpdate()` never reads it. It appears in builder stats for #6, #8, #10, and #18.",
        "- Template 15 (Freelancer) calls its career-goal section `What I Seek`; that label is not in `liveUpdate()`'s recognized goal labels. Its `p.about` is first overwritten with the About Me value and is not then replaced by the career goal value.",
        "- Certificates have no edit-panel input in the source; their existing rendering is data-fed, but the client editor has no certificate write-back control.",
        "- All edits are preview-only per the panel notice. Browser PDF/print uses the edited active preview through `buildStandaloneResumeHTML()`; `/resume_pdf` independently reloads database data.",
        "",
        "## Ranked root-cause hypotheses and browser checks",
        "",
        "1. **Shared selector/label coverage differs by design.** The updater targets generic classes and normalized section names (`templates/resume_builder.html:1995-2025`, `2105-2114`, `2157-2169`). Expected-working check: #1 Classic Tech, change Known Skills and Career Goal. Expected-failing check: #6 Data Scientist, change Known Skills; the bars have no rebuild sample (`1309`, `2158-2161`). Also check #15 Freelancer Career Goal (`1570`): What I Seek is not a recognized goal label and shares `p.about` with the summary.",
        "2. **Clean ATS (#2) only has a partial bespoke adapter.** Expected-working check: #2 Full Name or Professional Summary (`2046-2075`). Expected-failing check: #2 project title or Learning Skills; its DOM uses `t19-proj-*` (`1168-1179`), while the shared project updater requires `.pj/.pt/.pd` (`2105-2114`), and the #2 branch does not replace learning skills (`2046-2103`).",
        "3. **Years of Experience is a dead editor field.** Expected-working check: #1 change Full Name. Expected-failing check: #6 change Years of Experience; the stat at `templates/resume_builder.html:1292` stays unchanged because `liveUpdate()` does not read `ep-exp` (`1968-2155`).",
        "4. **Certificates have no editor control.** Expected-working check: #1 project title. Expected-failing check: #1 certificate name; panel fields contain no certificate input (`933-1000`).",
        "5. **Design count/name drift affects the server PDF selection.** Expected-working check: `/resume_pdf?t=1`; expected-failing check: `/resume_pdf?t=19`, which is clamped to #1 (`routes/resume_portfolio.py:86-90`). The builder has 19 cards/blocks; `TEMPLATE_NAMES` is an 18-entry mapping at `services/utils.py:47-52`, and its #2 label is Minimal Pro while builder #2 is Clean ATS (`templates/resume_builder.html:1025`).",
        "",
        "## Proposed minimal fix location (not applied)",
        "",
        "If approved, start in the shared `liveUpdate()` implementation (`templates/resume_builder.html:1967-2169`) by adding targeted selector/label adapters for exceptional designs; avoid changing 18–19 duplicated markup blocks. Certificate editing is a separate control/data-path decision. Resolve the 18-vs-19 server numbering decision separately before changing `TEMPLATE_NAMES` or the clamp.",
        "",
        "## Endpoint/template count discrepancy",
        "",
        "The builder source has 19 chooser cards and 19 preview blocks (`t1` through `t19`). `services/utils.py` defines only 18 `TEMPLATE_NAMES`, starting at line 47. Its current #2 name does not match the builder's Clean ATS #2, with subsequent labels offset by one. `routes/resume_portfolio.py` clamps values outside 1..18 to 1, so `/resume_pdf?t=19` is rendered as template 1. `templates/resume_pdf.html` nevertheless contains a `t19` block, but the route makes it unreachable through `t=19`.",
        "",
    ]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {REPORT}")
    print(f"Builder templates: {len(templates)}; duplicate IDs: {len(duplicates)}; missing literal ID refs: {len(missing)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
